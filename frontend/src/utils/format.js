const thaiMonths = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'];

export function formatThaiDate(value) {
  if (!value) return '-';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '-';
  return `${date.getDate()} ${thaiMonths[date.getMonth()]} ${date.getFullYear() + 543}`;
}

// Buddhist-era month/year for an `<input type="month">` value ("YYYY-MM"); display only.
// Parses the string directly: `new Date("YYYY-MM")` is UTC midnight and can roll to the wrong
// local month near a timezone boundary.
//
// Not named `formatThaiMonthYear`: specialMoneyRules.js exports a different function of that name
// (takes a `Date`), and a mistaken import would silently return '-'.
function monthYearFrom(value, monthNames) {
  const match = /^(\d{4})-(\d{2})$/.exec(value || '');
  const monthIndex = match ? Number(match[2]) - 1 : -1;
  if (monthIndex < 0 || monthIndex > 11) return '-';
  return `${monthNames[monthIndex]} ${Number(match[1]) + 543}`;
}

export function formatThaiMonthYearFromMonthInputValue(value) {
  return monthYearFrom(value, thaiMonths);
}

export const thaiMonthsLong = ['มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน', 'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม'];

// Full month name + BE year for a "YYYY-MM" value ("พฤศจิกายน 2569"); '-' when it is not one.
export function formatThaiMonthYearLongFromMonthInputValue(value) {
  return monthYearFrom(value, thaiMonthsLong);
}

export function formatShortDate(value) {
  if (!value) return '-';
  // A bare "YYYY-MM-DD" is parsed directly: `new Date(value)` reads it as UTC midnight, which rolls
  // to the previous day west of UTC. A full ISO datetime (a real instant) falls through to
  // `new Date()`, where reading it back in local time is correct.
  const dateOnly = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (dateOnly) {
    const [, year, month, day] = dateOnly;
    const monthIndex = Number(month) - 1;
    if (monthIndex < 0 || monthIndex > 11) return '-';
    return `${day}/${month}/${Number(year) + 543}`;
  }
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '-';
  return `${String(date.getDate()).padStart(2, '0')}/${String(date.getMonth() + 1).padStart(2, '0')}/${date.getFullYear() + 543}`;
}

/**
 * Canonical address formatter; do not re-add a page-local version.
 *
 * `currentAddress` is four separate fields (line1/district/province/postalCode),
 * and rendering only `line1` silently dropped the district, province and postcode.
 * Empty parts are filtered out because a newly created employee gets '' for
 * everything but `line1` (mockApi) — joining blindly would leave stray spaces.
 */
export function formatAddress(address) {
  if (!address) return '-';
  const parts = [address.line1, address.district, address.province, address.postalCode]
    .map((part) => (typeof part === 'string' ? part.trim() : part))
    .filter(Boolean);
  return parts.length > 0 ? parts.join(' ') : '-';
}

