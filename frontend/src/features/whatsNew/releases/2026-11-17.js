const RELEASE_ID = '2026-11-17';
const shot = (entryId, n) => `/whats-new/${RELEASE_ID}/${entryId}-${n}.png`;

function entry({ id, steps, ...rest }) {
  return {
    id,
    ...rest,
    steps: steps.map(([text, detail, alt], index) => ({ text, detail, alt, image: shot(id, index + 1) })),
  };
}

