// มีอะไรใหม่: v2.0.0 (20 พ.ย. 2569), the first notice under the version numbers (docs/versioning.md). It covers what
// is live on the develop branch since the 16 and 17 Nov notices, which were retired. The id, date label and screenshot
// folder are literals: a notice keeps its identity when the build version moves on.
//
// SHAPE. `entries` is one entry per page or document this release changed; `sections` says which entries each of the
// nine roles is told about. A role is listed only for a page it can open in production (audiences.js applies the
// release lockdown on top), and a role that sees the same change differently has its own entry, as -team / -finance.
// Who can do or see each thing follows the Java rules, not the mock:
//   - สั่งเพิ่ม: DealPartyService#createAddOnOrder (owner, keyer or all-sales-docs grant holder; ACTIVE deal). The
//     orders box and the order chips are read by anyone who can read the deal (requireOrderRead: sales, sales_manager, ceo; account inside
//     its finance scope; import has its own page, which shows neither).
//   - Deposit notice / remaining invoice: DepositNoticeService#requireTicketViewer. Read: sales (own deals),
//     sales_manager, ceo (all deals), account (finance scope: it downloads them from the finance page, no editor).
//     Write: the owner or keyer, or an all-sales-documents grant holder (mayWriteDealDocuments). import is refused.
//   - account's finance-page downloads: FinanceMilestoneSections DownloadButton -> /api/deposit-notices/{id}/file and
//     /api/remaining-invoices/{id}/file, which bundle through DocumentBundle with the remembered choice.
//   - Quotation PDF note: any quotation PDF or Excel, so every role that can open /quotations under the lock.
//
// Steps with no picture (alt null) are screens the mock app cannot show honestly (the PDF itself, the editor's
// customer lock and quotation picker). Every label in "straight quotes" is on screen today.
//
// SCREENSHOTS. One per step, at /whats-new/v2.0.0/<entry id>-<step number>.png (frontend/public/whats-new/…).

const RELEASE_ID = 'v2.0.0';
const shot = (entryId, n) => `/whats-new/${RELEASE_ID}/${entryId}-${n}.png`;

/** A step tuple is [text, detail, alt]; an alt of null means the step has NO screenshot (image null). The step keeps
 * its number, so the other images keep their paths. */
function entry({ id, steps, ...rest }) {
  return {
    id,
    ...rest,
    steps: steps.map(([text, detail, alt], index) => ({
      text, detail, alt, image: alt === null ? null : shot(id, index + 1),
    })),
  };
}

